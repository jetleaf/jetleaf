import 'package:jetleaf_core/lang.dart';
import 'package:meta/meta_meta.dart';

/// {@template jetleaf_id_annotation}
/// Marks a field as the **primary key identifier** of an `@Entity`.
///
/// Every persistent entity must declare an `@Id` field (either directly or
/// inherited from a superclass). When paired with `@GeneratedValue`, the
/// identifier value is automatically generated for newly inserted entities.
///
/// ### Usage Example
/// ```dart
/// @Entity()
/// class User {
///   @Id()
///   String? id;
/// }
/// ```
///
/// ### See Also
/// - [GeneratedValue]
/// - [Entity]
/// {@endtemplate}
@Target({TargetKind.field})
final class Id extends ReflectableAnnotation with EqualsAndHashCode {
  /// Reflective [Class] handle for [Id].
  static final Class<Id> CLASS = Class<Id>(null, PackageNames.DATA);

  /// {@macro jetleaf_id_annotation}
  const Id();

  @override
  Type get annotationType => Id;

  @override
  List<Object?> equalizedProperties() => [Id];
}

/// {@template jetleaf_generation_strategy}
/// Strategy used to produce primary key values for an `@Id` field annotated
/// with `@GeneratedValue`.
///
/// | Strategy | Description |
/// |----------|-------------|
/// | [autoIncrement] | Database-managed integer sequence (`BIGSERIAL`, `AUTO_INCREMENT`, `INTEGER PRIMARY KEY AUTOINCREMENT`) |
/// | [identity] | Database identity column (`GENERATED BY DEFAULT AS IDENTITY`) |
/// | [uuid] | RFC 4122 UUID v4 string generated by the framework before insert |
/// | [snowflake] | Time-ordered 64-bit integer identifier generated by the framework before insert |
/// {@endtemplate}
enum GenerationStrategy {
  /// Default database auto-increment sequence.
  autoIncrement,

  /// Database identity column.
  identity,

  /// Framework-generated RFC 4122 UUID v4 string.
  uuid,

  /// Framework-generated 64-bit snowflake identifier.
  snowflake;

  /// Returns `true` if this strategy delegates key generation to the database
  /// engine (`autoIncrement` or `identity`).
  bool isDatabaseGenerated() => this == autoIncrement || this == identity;
}

/// {@template jetleaf_generated_value_annotation}
/// Marks an `@Id` field as **automatically generated** by either the database
/// engine or the JetLeaf persistence runtime.
///
/// ### Usage Example
/// ```dart
/// @Entity()
/// class User {
///   @Id()
///   @GeneratedValue(strategy: GenerationStrategy.uuid)
///   String? id;
/// }
/// ```
///
/// ### See Also
/// - [Id]
/// - [GenerationStrategy]
/// {@endtemplate}
@Target({TargetKind.field})
final class GeneratedValue extends ReflectableAnnotation with EqualsAndHashCode {
  /// Reflective [Class] handle for [GeneratedValue].
  static final Class<GeneratedValue> CLASS = Class<GeneratedValue>(null, PackageNames.DATA);

  /// The identifier generation strategy.
  final GenerationStrategy strategy;

  /// {@macro jetleaf_generated_value_annotation}
  const GeneratedValue({this.strategy = GenerationStrategy.autoIncrement});

  @override
  Type get annotationType => GeneratedValue;

  @override
  List<Object?> equalizedProperties() => [strategy];
}