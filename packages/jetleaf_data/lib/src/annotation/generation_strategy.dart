/// {@template jetleaf_generation_strategy}
/// Strategy used to produce primary key values for an `@Id` field annotated
/// with `@GeneratedValue`.
///
/// | Strategy | Description |
/// |----------|-------------|
/// | [autoIncrement] | Database-managed integer sequence (`BIGSERIAL`, `AUTO_INCREMENT`, `INTEGER PRIMARY KEY AUTOINCREMENT`) |
/// | [identity] | Database identity column (`GENERATED BY DEFAULT AS IDENTITY`) |
/// | [uuid] | RFC 4122 UUID v4 string generated by the framework before insert |
/// | [snowflake] | Time-ordered 64-bit integer identifier generated by the framework before insert |
/// {@endtemplate}
enum GenerationStrategy {
  /// Default database auto-increment sequence.
  autoIncrement,

  /// Database identity column.
  identity,

  /// Framework-generated RFC 4122 UUID v4 string.
  uuid,

  /// Framework-generated 64-bit snowflake identifier.
  snowflake;

  /// Returns `true` if this strategy delegates key generation to the database
  /// engine (`autoIncrement` or `identity`).
  bool isDatabaseGenerated() => this == autoIncrement || this == identity;
}
