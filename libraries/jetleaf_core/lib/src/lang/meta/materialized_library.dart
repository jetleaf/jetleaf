/// Executes a reflected instance or static method in an AOT registry.
///
/// [instance] is the receiver for instance methods and is `null` for static
/// methods. [argument] contains the positional and named arguments prepared by
/// the reflection layer. The callback returns the method result, including
/// `null` for `void` methods.
typedef MethodExecutable = Object? Function(Object? instance, ExecutableArgument argument);

/// Constructs an object without runtime reflection.
///
/// The optional [argument] contains arguments for the selected constructor and
/// may be omitted when the constructor takes no parameters. Generated AOT
/// registries register one of these callbacks for each constructible type.
typedef ConstructorExecutable = Object Function([ExecutableArgument? argument]);

/// Reads a reflected field without runtime reflection.
///
/// [instance] is the owning object for an instance field and is `null` for a
/// static field. The callback returns the current field value.
typedef FieldGetterExecutable = Object? Function(Object? instance);

/// Writes a reflected field without runtime reflection.
///
/// [instance] is the owning object for an instance field and is `null` for a
/// static field. [value] is passed through without conversion; generated code
/// performs the assignment and therefore enforces Dart's normal type checks.
typedef FieldSetterExecutable = void Function(Object? instance, Object? value);

/// Resolves a serialized enum reference to its live enum constant.
///
/// The callback is intentionally lazy because enum constants cannot be stored
/// directly in the materialized metadata cache.
typedef EnumValueResolver = Object Function();

/// Materializes a live [Annotation] instance from reflection metadata.
///
/// [name] is the annotation's registered type name and [annotation] contains
/// the declaration metadata. Implementations return the matching annotation
/// instance, or `null` when the factory does not handle [name]. Factories are
/// evaluated in registration order.
typedef Annotable = Object? Function(String name, Annotation annotation);

/// Reconstructs an annotation from serialized declaration metadata.
///
/// [name] identifies the annotation type and [userProvidedValues] contains
/// only arguments explicitly supplied in source. This is used when metadata is
/// read from the build cache, where a live [Annotation] object is unavailable.
typedef AnnotationInstanceResolver = Object? Function(String name, Map<String, dynamic> userProvidedValues);

/// {@template materialized_library}
/// The materialized reflection registry used by the AOT runtime.
///
/// Ahead-of-time registries generated by `jl build` declare their compiled
/// closures against this class — never against executor, declaration, or
/// annotation internals. It is the single point of registration for:
///
/// - **Types** — [Type] tokens keyed by simple name, qualified name, and
///   `dart:`-prefixed names, used to resolve declared type references.
/// - **Annotations** — factories that materialize annotation instances from
///   reflection metadata, both for live annotated declarations ([Annotation])
///   and for declarations deserialized from the build cache.
/// - **Constructors** — named and type-based factories, plus [constructByName],
///   the lookup path used by annotations with `@JsonCreator`-style constructors.
/// - **Methods** — invokers keyed by `'ClassName.methodName'`.
/// - **Fields** — getters and setters keyed by `'ClassName.fieldName'`.
/// - **Enum values** — factories resolving a deserialized enum field declaration
///   back to its live constant, keyed by `'EnumName.valueName'`.
///
/// Generated code should only ever write to this class; application code never
/// needs to. Registries are initialized once per process and are not intended
/// to be cleared outside of test isolation helpers.
/// {@endtemplate}
final class MaterializedLibrary {
  /// {@macro materialized_library}
  MaterializedLibrary._();

