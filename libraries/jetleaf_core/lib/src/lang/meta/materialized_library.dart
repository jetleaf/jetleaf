  /// Registers [type] under [name] and, when supplied, [qualifiedName].
  ///
  /// When invoked with an explicit type argument `registerType<MyClass>(...)`,
  /// a [StandardTypeReifier] for `T` is also registered so the runtime can
  /// instantiate reified `List<T>`, `Set<T>`, and `Map<K, T>` collections.
  static void registerType<T>(String name, Type type, [String? qualifiedName, TypeReifier? reifier]) {
    _registeredTypes[name] = type;
    if (qualifiedName != null && qualifiedName.isNotEmpty) {
      _registeredTypes[qualifiedName] = type;
    }

    final effectiveReifier = reifier ??
        ((T != dynamic && (T != Object || type == Object))
            ? StandardTypeReifier<T>()
            : null);

    if (effectiveReifier != null) {
      _typeReifiersByType[type] = effectiveReifier;
      _typeReifiersByType[effectiveReifier.getType()] = effectiveReifier;
      _typeReifiersByName[name] = effectiveReifier;
      if (qualifiedName != null && qualifiedName.isNotEmpty) {
        _typeReifiersByName[qualifiedName] = effectiveReifier;
      }
    }
  }

  /// Registers a [StandardTypeReifier] for the compile-time type [T].
  ///
  /// Called automatically by `Class<T>` and generated AOT type registries so
  /// any reflected type `T` can produce reified generic collections.
  static void registerTypeReifier<T>([String? name, String? qualifiedName]) {
    if (T == dynamic) return;
    final reifier = StandardTypeReifier<T>();
    _typeReifiersByType[T] = reifier;
    final typeStr = T.toString();
    _typeReifiersByName[typeStr] = reifier;
    if (name != null && name.isNotEmpty) {
      _typeReifiersByName[name] = reifier;
    }
    if (qualifiedName != null && qualifiedName.isNotEmpty) {
      _typeReifiersByName[qualifiedName] = reifier;
    }
  }

  /// Looks up a [TypeReifier] by [type] and/or [name], recursively composing
  /// generic collection reifiers (`List<T>`, `Set<T>`, `Iterable<T>`, `Map<K, V>`)
  /// when needed.
  static TypeReifier? lookupTypeReifier({Type? type, String? name}) {
    if (type != null && type != dynamic && type != Object) {
      final direct = _typeReifiersByType[type];
      if (direct != null) return direct;
      final byTypeStr = _typeReifiersByName[type.toString()];
      if (byTypeStr != null) return byTypeStr;
    }

    if (name != null && name.isNotEmpty) {
      final trimmed = name.trim();
      final clean = trimmed.endsWith('?') ? trimmed.substring(0, trimmed.length - 1).trim() : trimmed;
      final directByName = _typeReifiersByName[clean];
      if (directByName != null) return directByName;

      if (clean.contains('.')) {
        final short = clean.split('.').last;
        final byShort = _typeReifiersByName[short];
        if (byShort != null) return byShort;
      }

      // Recursive generic composition for List<E>, Set<E>, Iterable<E>, Map<K, V>
      final ltIndex = clean.indexOf('<');
      if (ltIndex > 0 && clean.endsWith('>')) {
        final outer = clean.substring(0, ltIndex).trim();
        final outerShort = outer.contains('.') ? outer.split('.').last : outer;
        final innerRaw = clean.substring(ltIndex + 1, clean.length - 1).trim();

        if (outerShort == 'List' || outerShort == 'Iterable') {
          final innerNullable = innerRaw.endsWith('?');
          final innerReifier = lookupTypeReifier(name: innerRaw);
          if (innerReifier != null) {
            final composed = innerReifier.getListReifier(nullable: innerNullable);
            _typeReifiersByName[clean] = composed;
            return composed;
          }
        } else if (outerShort == 'Set') {
          final innerNullable = innerRaw.endsWith('?');
          final innerReifier = lookupTypeReifier(name: innerRaw);
          if (innerReifier != null) {
            final composed = innerReifier.getSetReifier(nullable: innerNullable);
            _typeReifiersByName[clean] = composed;
            return composed;
          }
        } else if (outerShort == 'Map') {
          final typeArgs = _splitTopLevelTypeArgs(innerRaw);
          if (typeArgs.length == 2) {
            final keyReifier = lookupTypeReifier(name: typeArgs[0]);
            final valNullable = typeArgs[1].trim().endsWith('?');
            final valReifier = lookupTypeReifier(name: typeArgs[1]);
            if (keyReifier != null && valReifier != null) {
              final composed = keyReifier.getMapReifierWithValue(valReifier, nullableValue: valNullable);
              _typeReifiersByName[clean] = composed;
              return composed;
            }
          }
        }
      }

      final resolvedType = resolveType(clean);
      if (resolvedType != Object || clean == 'Object' || clean == 'dart:core.Object') {
        final byResolved = _typeReifiersByType[resolvedType];
        if (byResolved != null) return byResolved;
      }
    }

    if (type == Object) {
      return _typeReifiersByType[Object];
    }

    return null;
  }

  /// Creates a strongly-typed `List<T>` from [elements].
  ///
  /// Resolves the target element reifier from [elementType] or [elementTypeName]
  /// when supplied; otherwise infers the uniform element runtime type from
  /// [elements] when non-empty.
  static List<Object?> reifyList(
    Iterable<dynamic> elements, {
    Type? elementType,
    String? elementTypeName,
    bool nullable = false,
  }) {
    final explicitReifier = lookupTypeReifier(type: elementType, name: elementTypeName);
    if (explicitReifier != null) {
      final isNullable = nullable || (elementTypeName?.trim().endsWith('?') ?? false);
      return explicitReifier.createList(elements, isNullable);
    }

    final list = elements is List ? elements : elements.toList();
    if (list.isEmpty) {
      return list;
    }

    final nonNull = list.where((e) => e != null).toList();
    if (nonNull.isNotEmpty) {
      final firstType = nonNull.first.runtimeType;
      final hasNull = nonNull.length != list.length || nullable;
      if (nonNull.every((e) => e.runtimeType == firstType)) {
        final inferredReifier = lookupTypeReifier(type: firstType, name: firstType.toString());
        if (inferredReifier != null) {
          return inferredReifier.createList(list, hasNull);
        }
      }
    }

    return list;
  }

  /// Creates a strongly-typed `Set<T>` from [elements].
  ///
  /// Resolves the target element reifier from [elementType] or [elementTypeName]
  /// when supplied; otherwise infers the uniform element runtime type from
  /// [elements] when non-empty.
  static Set<Object?> reifySet(
    Iterable<dynamic> elements, {
    Type? elementType,
    String? elementTypeName,
    bool nullable = false,
  }) {
    final explicitReifier = lookupTypeReifier(type: elementType, name: elementTypeName);
    if (explicitReifier != null) {
      final isNullable = nullable || (elementTypeName?.trim().endsWith('?') ?? false);
      return explicitReifier.createSet(elements, isNullable);
    }

    final list = elements is List ? elements : elements.toList();
    if (list.isEmpty) {
      return elements is Set<Object?> ? elements : <dynamic>{};
    }

    final nonNull = list.where((e) => e != null).toList();
    if (nonNull.isNotEmpty) {
      final firstType = nonNull.first.runtimeType;
      final hasNull = nonNull.length != list.length || nullable;
      if (nonNull.every((e) => e.runtimeType == firstType)) {
        final inferredReifier = lookupTypeReifier(type: firstType, name: firstType.toString());
        if (inferredReifier != null) {
          return inferredReifier.createSet(list, hasNull);
        }
      }
    }

    return elements is Set<Object?> ? elements : Set<dynamic>.from(list);
  }

  /// Creates a strongly-typed `Map<K, V>` from [entries].
  ///
  /// Resolves the key and value reifiers from [keyType]/[keyTypeName] and
  /// [valueType]/[valueTypeName] when supplied; otherwise infers uniform key
  /// and value runtime types from [entries] when non-empty.
  static Map<Object?, Object?> reifyMap(
    Map<dynamic, dynamic> entries, {
    Type? keyType,
    String? keyTypeName,
    Type? valueType,
    String? valueTypeName,
    bool nullableValue = false,
  }) {
    var keyReifier = lookupTypeReifier(type: keyType, name: keyTypeName);
    var valReifier = lookupTypeReifier(type: valueType, name: valueTypeName);
    var isNullableVal = nullableValue || (valueTypeName?.trim().endsWith('?') ?? false);

    if (keyReifier == null && entries.isNotEmpty) {
      final nonNullKeys = entries.keys.where((k) => k != null).toList();
      if (nonNullKeys.isNotEmpty) {
        final firstKeyType = nonNullKeys.first.runtimeType;
        if (nonNullKeys.every((k) => k.runtimeType == firstKeyType)) {
          keyReifier = lookupTypeReifier(type: firstKeyType, name: firstKeyType.toString());
        }
      }
    }

    if (valReifier == null && entries.isNotEmpty) {
      final nonNullVals = entries.values.where((v) => v != null).toList();
      if (nonNullVals.isNotEmpty) {
        final firstValType = nonNullVals.first.runtimeType;
        if (nonNullVals.length != entries.length) {
          isNullableVal = true;
        }
        if (nonNullVals.every((v) => v.runtimeType == firstValType)) {
          valReifier = lookupTypeReifier(type: firstValType, name: firstValType.toString());
        }
      } else if (keyReifier != null) {
        valReifier = const StandardTypeReifier<dynamic>();
      }
    }

    if (keyReifier != null && valReifier != null) {
      return keyReifier.createMapWithValue(valReifier, entries, isNullableVal);
    }

    if (keyReifier != null && keyReifier.getType() == String) {
      return Map<String, dynamic>.from(entries);
    }

    return entries;
  }

  /// Coerces a runtime collection [value] (`List`, `Set`, `Iterable`, or `Map`)
  /// into the exact reified generic collection expected by [targetTypeName].
  ///
  /// Used by generated AOT constructor/method invokers and annotation
  /// deserializers so `Function.apply` receives genuine `List<T>`, `Set<T>`,
  /// and `Map<K, V>` instances even for empty literals (`[]`, `{}`) or
  /// user-defined types.
  static dynamic coerceValue(dynamic value, [String? targetTypeName]) {
    if (value == null) return null;

    if (targetTypeName != null && targetTypeName.isNotEmpty) {
      final trimmed = targetTypeName.trim();
      final clean = trimmed.endsWith('?') ? trimmed.substring(0, trimmed.length - 1).trim() : trimmed;
      final ltIndex = clean.indexOf('<');
      if (ltIndex > 0 && clean.endsWith('>')) {
        final outer = clean.substring(0, ltIndex).trim();
        final outerShort = outer.contains('.') ? outer.split('.').last : outer;
        final innerRaw = clean.substring(ltIndex + 1, clean.length - 1).trim();

        if ((outerShort == 'List' || outerShort == 'Iterable') && value is Iterable) {
          final innerNullable = innerRaw.endsWith('?');
          final innerHasGenerics = innerRaw.contains('<');
          final elements = innerHasGenerics
              ? value.map((e) => coerceValue(e, innerRaw)).toList()
              : value;
          return reifyList(elements, elementTypeName: innerRaw, nullable: innerNullable);
        }

        if (outerShort == 'Set' && value is Iterable) {
          final innerNullable = innerRaw.endsWith('?');
          final innerHasGenerics = innerRaw.contains('<');
          final elements = innerHasGenerics
              ? value.map((e) => coerceValue(e, innerRaw)).toList()
              : value;
          return reifySet(elements, elementTypeName: innerRaw, nullable: innerNullable);
        }

        if (outerShort == 'Map' && value is Map) {
          final typeArgs = _splitTopLevelTypeArgs(innerRaw);
          if (typeArgs.length == 2) {
            final kType = typeArgs[0].trim();
            final vType = typeArgs[1].trim();
            final vNullable = vType.endsWith('?');
            final kHasGenerics = kType.contains('<');
            final vHasGenerics = vType.contains('<');
            final mappedEntries = (kHasGenerics || vHasGenerics)
                ? {
                    for (final entry in value.entries)
                      (kHasGenerics ? coerceValue(entry.key, kType) : entry.key):
                          (vHasGenerics ? coerceValue(entry.value, vType) : entry.value),
                  }
                : value;
            return reifyMap(
              mappedEntries,
              keyTypeName: kType,
              valueTypeName: vType,
              nullableValue: vNullable,
            );
          }
        }
      }
    }

    if (value is Set) {
      return reifySet(value);
    }
    if (value is List) {
      return reifyList(value);
    }
    if (value is Map) {
      return reifyMap(value);
    }
    return value;
  }

  static List<String> _splitTopLevelTypeArgs(String input) {
    final result = <String>[];
    var depth = 0;
    var start = 0;
    for (var i = 0; i < input.length; i++) {
      final ch = input[i];
      if (ch == '<') {
        depth++;
      } else if (ch == '>') {
        if (depth > 0) depth--;
      } else if (ch == ',' && depth == 0) {
        result.add(input.substring(start, i).trim());
        start = i + 1;
      }
    }
    final tail = input.substring(start).trim();
    if (tail.isNotEmpty) {
      result.add(tail);
    }
    return result;
  }

  /// Whether [name] is registered in the type table (checked strictly,
  /// without any synthesis), optionally willing to match base names of
  /// parameterised registrations.
  static bool hasRegisteredType(String name) {
    final clean = name.endsWith('?') ? name.substring(0, name.length - 1) : name;
    final base = clean.split('<').first;
    if (_registeredTypes.containsKey(clean)) return true;
    if (_registeredTypes.containsKey(base)) return true;
    if (base.startsWith('dart:') && base.contains('.')) {
      final short = base.split('.').last;
      if (_registeredTypes.containsKey(short)) return true;
    }
    return false;
  }

  /// Resolves [name], or optionally [fallbackName], to a Dart [Type].
  ///
  /// Nullable and generic syntax is ignored for lookup. Returns [Object] when
  /// neither name is registered.
  static Type resolveType(String name, [String? fallbackName]) {
    final clean = name.endsWith('?') ? name.substring(0, name.length - 1) : name;
    final base = clean.split('<').first;
    if (_registeredTypes.containsKey(clean)) return _registeredTypes[clean]!;
    if (_registeredTypes.containsKey(base)) return _registeredTypes[base]!;
    if (base.startsWith('dart:') && base.contains('.')) {
      final short = base.split('.').last;
      if (_registeredTypes.containsKey(short)) return _registeredTypes[short]!;
    }
    if (fallbackName != null && fallbackName.isNotEmpty) {
      final cleanFallback = fallbackName.endsWith('?')
          ? fallbackName.substring(0, fallbackName.length - 1)
          : fallbackName;
      final baseFallback = cleanFallback.split('<').first;
      if (_registeredTypes.containsKey(cleanFallback)) return _registeredTypes[cleanFallback]!;
      if (_registeredTypes.containsKey(baseFallback)) return _registeredTypes[baseFallback]!;
      if (baseFallback.startsWith('dart:') && baseFallback.contains('.')) {
        final short = baseFallback.split('.').last;
        if (_registeredTypes.containsKey(short)) return _registeredTypes[short]!;
      }
    }
    return Object;
  }

  // --------------------------------------------------------------------
  // Enum values
  // --------------------------------------------------------------------

  /// Lazy enum-value factories keyed by `'EnumName.valueName'`.
  ///
  /// Live enum constant instances cannot be serialized into the binary cache;
  /// instead, the generated code registers a factory per enum constant and
  /// declarations resolve their value lazily on first access.
  static final Map<String, Object Function()> _enumValueResolvers = <String, Object Function()>{};

  /// Registers [resolver] for the enum constant identified by [key].
  ///
  /// Keys use the `'EnumName.valueName'` form emitted by the generated registry.
  static void registerEnumValueResolver(String key, Object Function() resolver) {
    _enumValueResolvers[key] = resolver;
  }

  /// Resolves the enum constant registered under [key].
  ///
  /// Returns `null` when no resolver is registered, such as before registry
  /// initialization.
  static Object? resolveEnumValue(String key) => _enumValueResolvers[key]?.call();

  // --------------------------------------------------------------------
  // Constructors
  // --------------------------------------------------------------------

  /// Constructor factories indexed by their generated declaration name.
  static final Map<String, ConstructorExecutable> _namedConstructors = {};

  /// Constructor factories indexed by the runtime [Type] they construct.
  static final Map<Type, ConstructorExecutable> _typeConstructors = {};

  /// Registers [factory] to construct the declaration identified by [name].
  ///
  /// The name must match the key emitted into materialized metadata. A later
  /// registration for the same name replaces the previous factory.
  static void registerNamedConstructor(String name, ConstructorExecutable factory) {
    _namedConstructors[name] = factory;
  }

  /// Registers [factory] as the constructor for instances of [T].
  ///
  /// A later registration for [T] replaces the previous factory.
  static void registerConstructor<T>(ConstructorExecutable factory) {
    _typeConstructors[T] = factory;
  }

  /// Invokes the constructor factory registered under [name].
  ///
  /// Passes [argument] to the factory and returns `null` if no factory exists
  /// or the factory throws.
  static Object? constructByName(String name, [ExecutableArgument? argument]) {
    final factory = _namedConstructors[name];
    if (factory != null) {
      try {
        return factory(argument);
      } catch (_) {
        return null;
      }
    }
    return null;
  }

  /// Returns the constructor factory registered under [name], if any.
  ///
  /// Unlike [constructByName], this method does not invoke the factory.
  static ConstructorExecutable? lookupNamedConstructor(String name) => _namedConstructors[name];

  /// Returns the constructor factory registered for [type], if any.
  ///
  /// This method does not invoke the returned factory.
  static ConstructorExecutable? lookupTypeConstructor(Type type) => _typeConstructors[type];

  // --------------------------------------------------------------------
  // Methods
  // --------------------------------------------------------------------

  /// Method invokers indexed by generated `'ClassName.methodName'` keys.
  ///
  /// Each invoker receives the target instance, if required, and one
  /// [ExecutableArgument] representing the invocation arguments.
  static final Map<String, MethodExecutable> _methodInvokers = {};

  /// Registers [invoker] under [methodKey] for AOT method invocation.
  ///
  /// Registering the same key again replaces its existing invoker.
  static void registerMethod(String methodKey, MethodExecutable invoker) {
    _methodInvokers[methodKey] = invoker;
  }

  /// Returns the method invoker registered under [methodKey], if any.
  ///
  /// Callers supply the receiver and [ExecutableArgument] to the returned
  /// callback when they are ready to invoke the method.
  static MethodExecutable? lookupMethodInvoker(String methodKey) => _methodInvokers[methodKey];

  // --------------------------------------------------------------------
  // Fields
  // --------------------------------------------------------------------

  /// Field readers indexed by generated `'ClassName.fieldName'` keys.
  ///
  /// A reader accepts an instance receiver, or `null` for a static field.
  static final Map<String, FieldGetterExecutable> _fieldGetters = {};

  /// Field writers indexed by generated `'ClassName.fieldName'` keys.
  ///
  /// A writer accepts an instance receiver, or `null` for a static field.
  static final Map<String, FieldSetterExecutable> _fieldSetters = {};

  /// Registers [getter] under [fieldKey] for AOT field reads.
  ///
  /// Registering the same key again replaces its existing field reader.
  static void registerFieldGetter(String fieldKey, FieldGetterExecutable getter) {
    _fieldGetters[fieldKey] = getter;
  }

  /// Registers [setter] under [fieldKey] for AOT field writes.
  ///
  /// Registering the same key again replaces its existing field writer.
  static void registerFieldSetter(String fieldKey, FieldSetterExecutable setter) {
    _fieldSetters[fieldKey] = setter;
  }

  /// Returns the field getter registered under [fieldKey], if any.
  ///
  /// The returned callback is not invoked by this lookup.
  static FieldGetterExecutable? lookupFieldGetter(String fieldKey) => _fieldGetters[fieldKey];

  /// Returns the field setter registered under [fieldKey], if any.
  ///
  /// The returned callback is not invoked by this lookup.
  static FieldSetterExecutable? lookupFieldSetter(String fieldKey) => _fieldSetters[fieldKey];
}
